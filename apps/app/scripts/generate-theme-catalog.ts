// Writes theme-catalog.gen.ts and theme-loaders.gen.ts in src/lib/editor/themes
// from @uiw/codemirror-themes-all. The app reads theme names, modes and colors
// from the catalog, which every page loads, and the editor loads each CodeMirror
// extension from its own package only when needed.
// Run after upgrading the UIW theme packages: bun run themes:catalog
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { EditorState, EditorView, type Extension } from "@uiw/react-codemirror";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const themesDirectory = join(packageRoot, "src/lib/editor/themes");

export async function buildThemeCatalog() {
  const allEntry = Bun.resolveSync("@uiw/codemirror-themes-all", packageRoot);
  const allRoot = join(dirname(allEntry), "..");
  const manifest = (await Bun.file(join(allRoot, "package.json")).json()) as {
    dependencies: Record<string, string>;
  };
  const packages = Object.keys(manifest.dependencies).filter((name) =>
    name.startsWith("@uiw/codemirror-theme-"),
  );
  const themes = [];
  for (const pkg of packages) {
    const exports = (await import(Bun.resolveSync(pkg, allRoot))) as Record<
      string,
      unknown
    >;
    for (const [key, settings] of Object.entries(exports)) {
      if (!key.startsWith("defaultSettings")) continue;
      const suffix = key.slice("defaultSettings".length);
      const id = suffix.charAt(0).toLowerCase() + suffix.slice(1);
      const extension = exports[id] as Extension | undefined;
      if (!extension || !exports[`${id}Init`])
        throw new Error(`Missing UIW theme extension: ${pkg} ${id}`);
      const dark = EditorState.create({ extensions: [extension] }).facet(
        EditorView.darkTheme,
      );
      themes.push({
        id,
        name: suffix
          .replace(/([a-z])([A-Z])/g, "$1 $2")
          .replace(/^Github/, "GitHub")
          .replace(/^Vscode/, "VS Code"),
        mode: dark ? ("dark" as const) : ("light" as const),
        package: pkg,
        settings: settings as Record<string, string>,
      });
    }
  }
  return themes.sort((a, b) => a.name.localeCompare(b.name));
}

/** The generated files' contents by path. */
export async function renderThemeCatalog(): Promise<Record<string, string>> {
  const themes = await buildThemeCatalog();
  const entries = themes.map(
    (theme) =>
      `  ${JSON.stringify({ id: theme.id, name: theme.name, mode: theme.mode, settings: theme.settings })},`,
  );
  const loaders = themes.map(
    (theme) =>
      `  ${theme.id}: () => import(${JSON.stringify(theme.package)}).then((m) => m.${theme.id}),`,
  );
  const header =
    "// Generated by scripts/generate-theme-catalog.ts. Do not edit.\n";
  return {
    [join(themesDirectory, "theme-catalog.gen.ts")]: `${header}
export const themeCatalog = [
${entries.join("\n")}
] as const;

export type ThemeId = (typeof themeCatalog)[number]["id"];
`,
    [join(themesDirectory, "theme-loaders.gen.ts")]:
      `${header}import type { Extension } from "@uiw/react-codemirror";

import type { ThemeId } from "./theme-catalog.gen";

export const themeLoaders: Record<ThemeId, () => Promise<Extension>> = {
${loaders.join("\n")}
};
`,
  };
}

if (import.meta.main)
  for (const [path, text] of Object.entries(await renderThemeCatalog())) {
    await Bun.write(path, text);
    console.info(`Wrote ${path}`);
  }
